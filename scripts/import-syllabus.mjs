/* ==========================================================================
   The syllabus workbook → SQL for the content tables.

     node scripts/import-syllabus.mjs "<a .xlsx>" ["<another>" …]
       → supabase/import-syllabus.sql

   Takes as many workbooks as there are, because the courses do not all live
   in one: each course below names the book it is in and the sheet inside
   it. What the workbook means is in lib/syllabus.mjs; this is where it is
   decided which sheet is which course, and how that comes out as SQL.

   The SQL is idempotent: ids are derived from where a thing sits in the
   workbook, never random, so running it twice updates in place. It
   deliberately does not touch a session's `status` on the second run — the
   point of re-running is to bring new wording in, not to unpublish what is
   already in front of a class.
   ========================================================================== */

import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { readWorkbook } from './lib/xlsx.mjs'
import { contentOf, loopId, readCourse, sessionId, WORK_SESSION } from './lib/syllabus.mjs'

/* ---------------- what goes where ----------------
   The one block to edit. Everything below is mechanical. */

/** The program the four courses hang under, matched by name. */
const PROGRAM = 'Discovery Education Program'

/** In the order a hero takes them.
 *
 *  `book` is matched against the file names given on the command line, so a
 *  course can be rewritten in a workbook of its own without disturbing the
 *  other three — which is what happened to web design, where HTML and CSS
 *  grew Bootstrap and JavaScript and went from nine sessions to twelve.
 *
 *  `slug` only ever appears inside ids, so changing one renames every row it
 *  owns — which is to say, don't. */
const COURSES = [
  { book: 'HTML_CSS_Syllabus', sheet: 'Syllabus', slug: 'web', code: 'DSC-L1', name: 'Web Design Fundamentals (HTML, CSS, Bootstrap & JS)' },
  { book: 'IBSRA HEROS', sheet: 'electronics course', slug: 'mcu', code: 'DSC-L2', name: 'Microcontroller Fundamentals' },
  { book: 'IBSRA HEROS', sheet: 'Robotics Course', slug: 'rob', code: 'DSC-L3', name: 'Robotics Fundamentals (ESP32)' },
  { book: 'IBSRA HEROS', sheet: 'IOT-Electronics & Robotics', slug: 'iot', code: 'DSC-L4', name: 'IoT Fundamentals (ESP32, Firebase & Vercel)' },
]

/** A lecture, in minutes — LECTURE_HOURS in lib/programLength. A course's
 *  length is added up from its sessions, so this is what sets it. */
const SESSION_MIN = 120

/** The first course starts here, and each one follows a week after the one
 *  before it ends — the same chain `createLoop` makes in the store. Nothing
 *  in the workbook says when any of this runs, so these are placeholders
 *  for the admin to move. */
const FIRST_START = '2026-10-04'
const COURSE_WEEKS = 9

/* ---------------- SQL literals ---------------- */

const str = s => `'${String(s).replace(/'/g, "''")}'`
const nul = s => (s == null ? 'null' : str(s))
const pad = n => String(n).padStart(2, '0')

/** JSON goes in dollar-quoted, so none of its quotes or backslashes need
 *  doubling. The tag is checked against the payload rather than assumed. */
function json(value) {
  const text = JSON.stringify(value)
  if (text.includes('$syl$')) throw new Error('content contains the quoting tag $syl$')
  return `$syl$${text}$syl$::jsonb`
}

const at = (iso, days) =>
  new Date(Date.parse(iso + 'T09:00:00.000Z') + days * 864e5).toISOString()

/* ---------------- the file ---------------- */

function sqlFor(courses) {
  const out = []
  const w = s => out.push(s)

  w('-- ==========================================================================')
  w('-- The syllabus workbook, as rows.')
  w('--')
  w('-- Generated by scripts/import-syllabus.mjs — do not hand-edit; edit the')
  w('-- workbook and run it again. Safe to re-run: every id is derived from the')
  w('-- workbook, so a second run updates in place instead of adding a copy.')
  w('--')
  w('-- Sessions come in as drafts. Nothing here is in front of a student until')
  w('-- someone publishes it, and re-running never changes a status back.')
  w('-- ==========================================================================')
  w('')
  w('begin;')
  w('')
  w('-- Everything hangs under one program, matched by name so this file carries')
  w('-- no id that only exists in one database.')
  w('do $guard$')
  w('begin')
  w(`  if not exists (select 1 from public.tracks where name = ${str(PROGRAM)}) then`)
  w(`    raise exception 'no program named %', ${str(PROGRAM)};`)
  w('  end if;')
  w('end')
  w('$guard$;')
  w('')

  let start = FIRST_START
  for (const [i, c] of courses.entries()) {
    const startIso = at(start, 0)
    const endIso = at(start, COURSE_WEEKS * 7)
    start = new Date(Date.parse(endIso) + 7 * 864e5).toISOString().slice(0, 10)

    const overview = c.sessions.map((s, n) => `- Session ${n + 1} — ${s.name}`).join('\n')

    w('-- ---------------------------------------------------------------------')
    w(`-- ${c.name} · ${c.sessions.length} sessions`)
    w('-- ---------------------------------------------------------------------')
    w('insert into public.loops')
    w('  (id, track_id, code, name, idx, start_date, end_date, status, kind,')
    w('   listed, price_egp, lectures_per_week, duration_hours, overview)')
    w(`select ${str(loopId(c.slug))}, t.id, ${str(c.code)}, ${str(c.name)}, ${i + 1},`)
    w(`       ${str(startIso)}, ${str(endIso)}, 'planning', 'training',`)
    w(`       true, null, 1, null, ${str(overview)}`)
    w(`  from public.tracks t where t.name = ${str(PROGRAM)}`)
    w('on conflict (id) do update set')
    w('  code = excluded.code, name = excluded.name, idx = excluded.idx,')
    w('  overview = excluded.overview;')
    w('')

    for (const [n, s] of c.sessions.entries()) {
      /* The build weeks are the one place the workbook disagrees with its
         course: a training course, with its graduation session set apart. */
      const kind = WORK_SESSION.test(s.name) ? 'work' : null
      const { content, keys } = contentOf(c.slug, n, s.titles)
      const projects = content.titles.filter(t => t.kind === 'project').length
      const clips = content.titles.reduce(
        (a, t) => a + t.materials.filter(m => m.kind === 'video').length, 0)
      const asks = content.titles.reduce((a, t) => a + t.tasks.length, 0)

      w(`-- S${pad(n + 1)} ${s.name} · ${content.titles.length - projects} topics, ${projects} projects, ${clips} recordings, ${asks} questions${kind ? ` · ${kind} session` : ''}`)
      w('insert into public.sessions')
      w('  (id, loop_id, code, name, summary, type, status, sort_order,')
      w('   instructor_id, scheduled_at, duration_min, recording_ready, content, kind)')
      w('values')
      w(`  (${str(sessionId(c.slug, n))}, ${str(loopId(c.slug))}, ${str(`${c.code}-S${pad(n + 1)}`)},`)
      w(`   ${str(s.name)}, '', 'recorded', 'draft', ${n},`)
      w(`   null, null, ${SESSION_MIN}, false, ${json(content)}, ${nul(kind)})`)
      w('on conflict (id) do update set')
      w('  loop_id = excluded.loop_id, code = excluded.code, name = excluded.name,')
      w('  sort_order = excluded.sort_order, duration_min = excluded.duration_min,')
      w('  content = excluded.content, kind = excluded.kind,')
      w('  rev = public.sessions.rev + 1;')

      /* The model answers. They are kept out of `content` by the table
         itself, which refuses a document with a `modelAnswer` anywhere in
         it — a student can read `content`, and only an admin reads this. */
      w('insert into public.session_keys (session_id, keys)')
      w(`values (${str(sessionId(c.slug, n))}, ${json(keys)})`)
      w('on conflict (session_id) do update set keys = excluded.keys;')
      w('')
    }

    /* A course can lose sessions as well as gain them — web design was
       rewritten from nine to twelve. Only rows this script wrote are in
       range, by the shape of their id. Nothing a student touched can go
       this way: submissions and mentor feedback reference a session with
       `on delete restrict`, so a session with work on it raises instead of
       disappearing, which is the right way round. */
    const kept = c.sessions.map((_, n) => str(sessionId(c.slug, n))).join(', ')
    w('-- sessions this course used to have and no longer does')
    w('delete from public.sessions s')
    w(` where s.loop_id = ${str(loopId(c.slug))}`)
    w(`   and s.id like ${str(`ses_syl${c.slug}%`)}`)
    w(`   and s.id not in (${kept});`)
    w('')
  }

  w('commit;')
  w('')
  return out.join('\n')
}

/* ---------------- run ---------------- */

const here = path.dirname(fileURLToPath(import.meta.url))
const sources = process.argv.slice(2)
if (!sources.length) {
  console.error('usage: node scripts/import-syllabus.mjs "<a .xlsx>" ["<another>" …]')
  process.exit(2)
}

const books = sources.map(file => ({ file, name: path.basename(file), sheets: readWorkbook(file) }))

const courses = COURSES.map(c => {
  /* A sheet name like "Syllabus" says nothing about which course it is, so
     the book has to be named too, or two workbooks would collide. */
  const book = books.find(b => b.name.includes(c.book) && b.sheets.has(c.sheet))
  if (!book) {
    const had = books.map(b => `${b.name}: ${[...b.sheets.keys()].join(', ')}`).join('\n  ')
    throw new Error(`no sheet "${c.sheet}" in a workbook named like "${c.book}". Given:\n  ${had}`)
  }
  return { ...c, from: book.name, sessions: readCourse(book.sheets.get(c.sheet)) }
})

const target = path.join(here, '..', 'supabase', 'import-syllabus.sql')
writeFileSync(target, sqlFor(courses))

let sessions = 0, topics = 0, projects = 0, tasks = 0, clips = 0, files = 0, work = 0
for (const c of courses) {
  console.log(`${c.name}  ·  ${c.from} › ${c.sheet}`)
  for (const [n, s] of c.sessions.entries()) {
    const { titles } = contentOf(c.slug, n, s.titles).content
    const built = titles.filter(t => t.kind === 'project')
    const nClips = titles.reduce((a, t) => a + t.materials.filter(m => m.kind === 'video').length, 0)
    const nAsks = titles.reduce((a, t) => a + t.tasks.length, 0)
    const isWork = WORK_SESSION.test(s.name)
    sessions++
    topics += titles.length - built.length
    projects += built.length
    tasks += nAsks
    clips += nClips
    files += titles.reduce((a, t) => a + t.materials.filter(m => m.kind !== 'video').length, 0)
    work += isWork ? 1 : 0
    console.log(
      `  S${pad(n + 1)} ${s.name.slice(0, 44).padEnd(44)}` +
      ` ${String(titles.length - built.length).padStart(2)} topics ` +
      ` ${built.length} projects ` +
      ` ${String(nClips).padStart(2)} videos ` +
      ` ${String(nAsks).padStart(2)} questions` +
      (isWork ? '   [work session]' : ''))
  }
}
console.log(`\n${courses.length} courses · ${sessions} sessions (${work} work) · ${topics} topics · ${projects} projects · ${clips} recordings · ${tasks} questions · ${files} files`)
console.log(`\nwrote ${path.relative(process.cwd(), target)}`)
